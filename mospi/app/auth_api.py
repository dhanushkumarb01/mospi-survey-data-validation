"""Sign-in, sign-out, password change and account management routes, and the per-request session check used by api.py.

* ``POST /api/auth/login`` sets the session cookie (mospi/auth/sessions.py); ``POST /api/auth/logout`` clears it.
* ``POST /api/auth/password``: the account holder sets their own password (required after an account is created or reset).
* ``/api/users``: administrators create supervisor and analyst accounts, reset their passwords, change their role and
  deactivate them.  A new or reset password is generated by the server and returned once, to be passed on through a
  separate channel.  Administrator accounts are never created or changed here (python -m mospi.auth).

Brute force: five failed sign-ins lock an account for 15 minutes where the store keeps counts; every instance also limits
failed attempts per username and per client in memory.
"""
from __future__ import annotations

import logging
import threading
import time
from collections import deque
from typing import Any

from fastapi import FastAPI, HTTPException, Request, Response
from starlette.concurrency import run_in_threadpool

from mospi.auth import AccountError, ROLE_LABELS, CREATABLE_ROLES, UserStore, can, capabilities
from mospi.auth.passwords import MAX_LENGTH, burn_time, hash_password, password_problem, temporary_password, verify_password
from mospi.auth.sessions import COOKIE, SessionSigner
from mospi.auth.store import is_locked, normalise_username, public

LOG = logging.getLogger("MoSPI.auth")
SIGN_IN_REFUSED = "The username or password is not correct."
LOCKED = "This account is locked for 15 minutes after repeated failed sign-ins. Try again later, or ask an administrator to reset the password."
THROTTLED = "Too many failed sign-ins from here. Wait 15 minutes and try again."
NOT_CONFIGURED = "Sign-in is not configured on this instance (MOSPI_SESSION_SECRET is missing), so no data is served."
PASSWORD_CHANGE_REQUIRED = "Choose your own password before continuing."
PASSWORD_ELSEWHERE = "Passwords for this account are changed on the processing machine."
# Reachable without a session (they say only whether sign-in is needed, or perform it).
PUBLIC_ROUTES = {"/api/session/required", "/api/auth/login"}
# Reachable while the account must still choose its own password.
PASSWORD_ROUTES = {"/api/session", "/api/auth/password", "/api/auth/logout", "/api/labels", "/api/deployment", "/api/version"}
SESSION_CACHE_SECONDS = 15


class Throttle:
    """Failed sign-ins per username and per client within a window, in this process's memory."""

    def __init__(self, per_name: int = 10, per_client: int = 30, window: float = 900.0) -> None:
        self.limits = {"name": per_name, "client": per_client}
        self.window = window
        self._failures: dict[tuple[str, str], deque[float]] = {}
        self._lock = threading.Lock()

    def _recent(self, key: tuple[str, str], now: float) -> deque[float]:
        times = self._failures.setdefault(key, deque())
        while times and times[0] < now - self.window:
            times.popleft()
        return times

    def blocked(self, username: str, client: str) -> bool:
        now = time.monotonic()
        with self._lock:
            return (len(self._recent(("name", username), now)) >= self.limits["name"]
                    or len(self._recent(("client", client), now)) >= self.limits["client"])

    def failed(self, username: str, client: str) -> None:
        now = time.monotonic()
        with self._lock:
            if len(self._failures) > 10_000:          # bounded memory: forget everything rather than grow without limit
                self._failures.clear()
            self._recent(("name", username), now).append(now)
            self._recent(("client", client), now).append(now)


class Authenticator:
    def __init__(self, store: UserStore, signer: SessionSigner | None, *, hosted: bool) -> None:
        self.store, self.signer, self.hosted = store, signer, hosted
        self.throttle = Throttle()
        self._cache: dict[int, tuple[float, dict[str, Any] | None]] = {}
        self._lock = threading.Lock()

    # ---------------------------------------------------------------- sessions

    def session_account(self, user_id: int) -> dict[str, Any] | None:
        now = time.monotonic()
        with self._lock:
            cached = self._cache.get(user_id)
        if cached and cached[0] > now:
            return cached[1]
        account = self.store.session_record(user_id)
        with self._lock:
            self._cache[user_id] = (now + SESSION_CACHE_SECONDS, account)
        return account

    def forget(self, user_id: int) -> None:
        with self._lock:
            self._cache.pop(int(user_id), None)

    def user_for(self, request: Request) -> dict[str, Any] | None:
        """The signed-in user of a request (None: no valid session).  May raise DatabaseUnavailable."""
        if self.signer is None:
            return None
        session = self.signer.read(request.cookies.get(COOKIE))
        if session is None:
            return None
        account = self.session_account(session[0])
        if account is None or not account["active"] or account["session_version"] != session[1]:
            return None
        return {"user_id": account["user_id"], "username": account["username"], "name": account["display_name"], "role": account["role"],
                "must_change_password": bool(account["must_change_password"]) and self.can_change_own(account)}

    def can_change_own(self, account: dict[str, Any]) -> bool:
        # The hosted reviewer function never changes an administrator's password, so it is not demanded there.
        return self.store.can_change_password and not (self.hosted and account["role"] == "admin")

    def set_cookie(self, response: Response, request: Request, account: dict[str, Any]) -> None:
        secure = self.hosted or request.url.scheme == "https" or request.headers.get("x-forwarded-proto", "") == "https"
        response.set_cookie(COOKIE, self.signer.issue(account["user_id"], account["session_version"]), max_age=self.signer.lifetime,
                            httponly=True, samesite="strict", secure=secure, path="/")

    def client(self, request: Request) -> str:
        if self.hosted:   # Vercel sets these; locally they could be forged, so only the socket address counts there
            forwarded = request.headers.get("x-real-ip") or request.headers.get("x-forwarded-for", "").split(",")[0].strip()
            if forwarded:
                return forwarded
        return request.client.host if request.client else "unknown"


def session_payload(auth: Authenticator | None, user: dict[str, Any] | None) -> dict[str, Any]:
    return {"authentication": auth is not None, "user": user, "capabilities": capabilities(user),
            "role_label": ROLE_LABELS.get(user["role"]) if user else None,
            "can_change_password": bool(auth and user and auth.can_change_own(user)),
            "accounts_managed_here": bool(auth and auth.store.can_manage)}


def register(app: FastAPI, auth: Authenticator | None) -> None:
    def signed_in(request: Request) -> dict[str, Any]:
        user = getattr(request.state, "user", None)
        if auth is None or user is None:
            raise HTTPException(401, "Authentication required.")
        return user

    def administrator(request: Request) -> dict[str, Any]:
        user = signed_in(request)
        if not can(user, "manage_users"):
            raise HTTPException(403, "Only an administrator can manage accounts.")
        if not auth.store.can_manage:
            raise HTTPException(403, "Accounts are managed on the processing machine.")
        return user

    def account_call(function, *args, **kwargs):
        try:
            return function(*args, **kwargs)
        except AccountError as error:
            raise HTTPException(error.status, str(error)) from error

    @app.post("/api/auth/login")
    def login(payload: dict[str, Any], request: Request, response: Response) -> dict[str, Any]:
        if auth is None:
            raise HTTPException(404, "Sign-in is not used on this instance.")
        if auth.signer is None:
            raise HTTPException(503, NOT_CONFIGURED)
        username, password = normalise_username(payload.get("username")), str(payload.get("password") or "")
        client = auth.client(request)
        if not username or not password or len(username) > 40 or len(password) > MAX_LENGTH:
            raise HTTPException(401, SIGN_IN_REFUSED)
        if auth.throttle.blocked(username, client):
            raise HTTPException(429, THROTTLED)
        account = auth.store.login_record(username)
        if account is None:
            burn_time(password)
            verified = False
        else:
            verified = verify_password(password, account["password_hash"])
        if account is not None and is_locked(account):
            auth.throttle.failed(username, client)
            raise HTTPException(423, LOCKED)
        verified = verified and bool(account["active"])
        if auth.store.records_attempts:
            try:
                auth.store.note_attempt(username, verified)
            except Exception as error:   # noqa: BLE001 - recording the outcome must not decide it; the cause is logged
                LOG.error("Sign-in outcome not recorded: %s", type(error).__name__)
        if not verified:
            auth.throttle.failed(username, client)
            raise HTTPException(401, SIGN_IN_REFUSED)
        auth.forget(account["user_id"])
        auth.set_cookie(response, request, account)
        user = {"user_id": account["user_id"], "username": account["username"], "name": account["display_name"], "role": account["role"],
                "must_change_password": bool(account["must_change_password"]) and auth.can_change_own(account)}
        return session_payload(auth, user)

    @app.post("/api/auth/logout")
    def logout(request: Request, response: Response) -> dict[str, Any]:
        user = getattr(request.state, "user", None)
        response.delete_cookie(COOKIE, path="/", httponly=True, samesite="strict")
        if auth is not None and user is not None and auth.store.can_manage:
            try:
                auth.store.log("SIGNED_OUT", user["username"], user["username"])
            except Exception as error:   # noqa: BLE001
                LOG.error("Sign-out not recorded: %s", type(error).__name__)
        return {"signed_out": True}

    @app.post("/api/auth/password")
    def change_password(payload: dict[str, Any], request: Request, response: Response) -> dict[str, Any]:
        user = signed_in(request)
        current, new = str(payload.get("current_password") or ""), str(payload.get("new_password") or "")
        if not auth.can_change_own(user):
            raise HTTPException(403, PASSWORD_ELSEWHERE)
        account = auth.store.login_record(user["username"])
        if account is None or len(current) > MAX_LENGTH or not verify_password(current, account["password_hash"]):
            raise HTTPException(400, "Your current password is not correct.")
        problem = password_problem(new, username=account["username"], display_name=account["display_name"])
        if problem is None and new == current:
            problem = "Choose a password different from the current one."
        if problem:
            raise HTTPException(400, problem)
        if not auth.store.change_password(account["user_id"], account["password_hash"], hash_password(new)):
            raise HTTPException(409, "The password was not changed; it was changed elsewhere at the same time. Sign in again.")
        auth.forget(account["user_id"])
        fresh = auth.store.session_record(account["user_id"])
        auth.set_cookie(response, request, fresh)
        return session_payload(auth, {**user, "must_change_password": False})

    @app.get("/api/users")
    def list_users(request: Request) -> dict[str, Any]:
        administrator(request)
        return {"users": [public(a) for a in account_call(auth.store.list_users)], "roles": list(CREATABLE_ROLES),
                "role_labels": ROLE_LABELS, "activity": [{**e, "event_utc": e["event_utc"].isoformat() if hasattr(e["event_utc"], "isoformat") else e["event_utc"]}
                                                         for e in account_call(auth.store.events, 40)]}

    @app.post("/api/users")
    def create_user(payload: dict[str, Any], request: Request) -> dict[str, Any]:
        admin = administrator(request)
        password = temporary_password()
        account = account_call(auth.store.create, username=str(payload.get("username") or ""), display_name=str(payload.get("display_name") or ""),
                               role=str(payload.get("role") or ""), password_hash=hash_password(password), created_by=admin["name"])
        return {"user": public(account), "temporary_password": password}

    @app.patch("/api/users/{user_id}")
    def update_user(user_id: int, payload: dict[str, Any], request: Request) -> dict[str, Any]:
        admin = administrator(request)
        if user_id == admin["user_id"]:
            raise HTTPException(403, "You cannot change your own account here.")
        active = payload.get("active")
        account = account_call(auth.store.update, user_id, actor=admin["name"], role=payload.get("role"), display_name=payload.get("display_name"),
                               active=None if active is None else bool(active))
        auth.forget(user_id)
        return {"user": public(account)}

    @app.post("/api/users/{user_id}/password")
    def reset_password(user_id: int, request: Request) -> dict[str, Any]:
        admin = administrator(request)
        if user_id == admin["user_id"]:
            raise HTTPException(403, "Change your own password with Change password.")
        password = temporary_password()
        account = account_call(auth.store.reset_password, user_id, hash_password(password), actor=admin["name"])
        auth.forget(user_id)
        return {"user": public(account), "temporary_password": password}


async def resolve_user(auth: Authenticator, request: Request) -> dict[str, Any] | None:
    return await run_in_threadpool(auth.user_for, request)
